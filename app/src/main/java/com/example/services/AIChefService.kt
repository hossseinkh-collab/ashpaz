package com.example.services

import com.example.data.Recipe

data class ChatMessageItem(
    val id: String,
    val isUser: Boolean,
    val text: String,
    val timestamp: String = "همین الان"
)

object AIChefService {

    fun getChefResponse(userQuery: String, activeRecipe: Recipe? = null): String {
        val q = userQuery.trim().lowercase()

        // Contextual recipe answers
        if (activeRecipe != null) {
            if (q.contains("چند دقیقه") || q.contains("زمان") || q.contains("تایم")) {
                return "برای پخت «${activeRecipe.title}»:\n" +
                        "⏱ زمان آماده‌سازی: ${activeRecipe.prepTimeMinutes} دقیقه\n" +
                        "🔥 زمان پخت روی شعله: ${activeRecipe.cookTimeMinutes} دقیقه\n" +
                        "توصیه سرآشپز: حتماً با شعله ملایم اجازه دهید غذا جا بیفتد."
            }
            if (q.contains("کالری") || q.contains("رژیم") || q.contains("چاق")) {
                return "ارزش غذایی هر سهم «${activeRecipe.title}»:\n" +
                        "• کالری: ${activeRecipe.caloriesPerServing} کیلوکالری\n" +
                        "• پروتئین: ${activeRecipe.proteinGrams} گرم\n" +
                        "• کربوهیدرات: ${activeRecipe.carbsGrams} گرم\n" +
                        "• چربی: ${activeRecipe.fatGrams} گرم\n" +
                        "اگر رژیم کاهش وزن دارید، سهم برنج یا نان کنار غذا را به ۶ تا ۸ قاشق محدود کنید."
            }
            if (q.contains("نکته") || q.contains("فوت") || q.contains("راز")) {
                val tips = activeRecipe.goldenTips.joinToString("\n• ")
                return "فوت‌وفن‌های طلایی پخت «${activeRecipe.title}»:\n• $tips"
            }
        }

        // Broad culinary knowledge base
        return when {
            q.contains("شور") -> {
                "اگر خورشتان شور شده است، نگران نباشید! این چند راهکار جادویی سرآشپز را به کار ببرید:\n" +
                        "۱. یک عدد سیب‌زمینی را پوست بگیرید، دو نیم کنید و در خورش بیندازید؛ نمک اضافی را به خود جذب می‌کند (قبل از سرو خارج کنید).\n" +
                        "۲. افزودن ۱ حبه قند کوچک همراه با ۱ قاشق چای‌خوری آبلیموی تازه.\n" +
                        "۳. اضافه کردن مقداری آب جوش تازه و کشیدن کمی از آب نمک‌دار خورش.\n" +
                        "۴. افزودن ۱ قاشق غذاخوری ماست یا خامه در خورش‌های سفید یا سوپ‌ها."
            }
            q.contains("روغن انداختن") || (q.contains("قورمه") && q.contains("روغن")) -> {
                "برای روغن انداختن عالی قورمه‌سبزی و فسنجان:\n" +
                        "۱. در ۱۰ دقیقه پایانی پخت، ۲ تا ۳ تکه یخ قالبی کوچک داخل خورش بیندازید؛ شوک دمایی باعث می‌شود روغن خورش بلافاصله به سطح بیاید.\n" +
                        "۲. سبزی قورمه را حتماً با حرارت بسیار ملایم و روغن کافی خوب سرخ کنید تا تیره شود اما نسوزد.\n" +
                        "۳. در طول پخت در قابلمه را نیمه‌باز بگذارید تا بخار اضافی خارج شود."
            }
            q.contains("برنج") && (q.contains("قد") || q.contains("دان") || q.contains("مجلسی")) -> {
                "راز قد کشیدن و دون شدن برنج مجلسی ایرانی:\n" +
                        "۱. برنج ایرانی را حداقل ۲ تا ۳ ساعت قبل با آب ولرم و ۲ قاشق نمک سنگ خیس کنید.\n" +
                        "۲. هنگام جوشیدن برنج، وقتی دانه‌ها بالا آمدند، ۱ لیوان آب یخ یا چند تکه یخ داخل قابلمه بریزید؛ این شوک سرمایی باعث قد کشیدن فوق‌العاده برنج می‌شود.\n" +
                        "۳. برنج را موقعی آبکش کنید که مغز دانه کمی زنده و دور آن نرم باشد.\n" +
                        "۴. دم‌کنی ضخیم و مناسب روی قابلمه بگذارید و ۱۰ دقیقه اول حرارت را متوسط و سپس ملایم کنید."
            }
            q.contains("پف") && (q.contains("کیک") || q.contains("شیرینی")) -> {
                "دلایل پف نکردن کیک خانگی و راه‌حل سرآشپز:\n" +
                        "۱. تخم‌مرغ و شیر باید حتماً حداقل ۳۰ دقیقه قبل از یخچال بیرون آمده و به دمای محیط رسیده باشند.\n" +
                        "۲. آرد و بکینگ‌پودر را حتماً ۳ بار الک کنید تا هواگیری شود.\n" +
                        "۳. زرده و سفیده یا تخم‌مرغ با شکر را با همزن برقی حداقل ۵ تا ۷ دقیقه بزنید تا کرم‌رنگ و کش‌دار شود.\n" +
                        "۴. بعد از افزودن آرد، فقط با لیسک و در یک جهت به آرامی به صورت دورانی فولد کنید و هرگز با همزن برقی نزنید.\n" +
                        "۵. فر را حتماً ۱۵ دقیقه قبل با دمای ۱۷۵ درجه گرم کنید و در ۲۰ دقیقه اول درب فر را هرگز باز نکنید."
            }
            q.contains("لیمو") && (q.contains("تلخ") || q.contains("عمانی")) -> {
                "روش صددرصد تضمینی برای گرفتن تلخی لیمو عمانی:\n" +
                        "۱. با چنگال چند سوراخ روی لیموها ایجاد کنید.\n" +
                        "۲. آن‌ها را در یک کاسه آب جوش به مدت ۱۵ دقیقه قرار دهید و سپس آب آن را دور بریزید.\n" +
                        "۳. حتی بهتر: لیمو را بشکنید، هسته‌های سیاه درون آن را کاملاً جدا کنید؛ بیشترین تلخی لیمو عمانی از هسته‌های آن است!"
            }
            q.contains("ته دیگ") || q.contains("ته‌دیگ") -> {
                "فوت کوزه‌گری برای ته دیگ برشته و طلایی زعفرانی:\n" +
                        "۱. کف قابلمه نچسب مقداری روغن مایع و ۲ قاشق زعفران دم‌کرده بریزید و بگذارید داغ شود.\n" +
                        "۲. برای ته‌دیگ سیب‌زمینی: حلقه‌های سیب‌زمینی را ۵ دقیقه در آب سرد بگذارید و خشک کنید، سپس کمی کنجد کف قابلمه بپاشید و سیب‌زمینی‌ها را بچینید.\n" +
                        "۳. برای ته‌دیگ ماستی: ۲ قاشق ماست چکیده + ۱ زرده تخم‌مرغ + ۲ قاشق زعفران غلیظ + ۱ قاشق روغن را مخلوط کرده و با ۲ کفگیر برنج ترکیب کنید و کف قابلمه صاف نمایید."
            }
            q.contains("تند") -> {
                "اگر غذایتان خیلی تند شده است:\n" +
                        "۱. مقداری آبلیموی تازه یا سرکه سیب اضافه کنید (اسید کپسایسین فلفل را خنثی می‌کند).\n" +
                        "۲. سرو غذا همراه با ماست، دوغ یا خامه.\n" +
                        "۳. افزودن کمی شکر یا عسل به سس غذا برای ایجاد توازن طعم."
            }
            q.contains("جایگزین") || q.contains("عوض") -> {
                "جایگزینی‌های طلایی آشپزی:\n" +
                        "• به جای خامه: ماست یونانی چکیده + کمی کره ذوب‌شده\n" +
                        "• به جای تخم‌مرغ در کیک: یک‌چهارم پیمانه پوره موز یا ماست شیرین\n" +
                        "• به جای سرکه بالزامیک: سرکه انگور + شیره خرما یا انگور\n" +
                        "• به جای کره: روغن مایع (۸۰٪ مقدار کره)"
            }
            else -> {
                "سلام! من سرآشپز هوشمند شما هستم 👨‍🍳\n" +
                        "در هر مرحله از پخت، آماده‌سازی مواد، تکنیک‌های اصیل پلو و خورش ایرانی، فست‌فود، قنادی یا رژیم و کالری غذاها سوالی دارید، بپرسید تا با دقیق‌ترین متدهای سرآشپزی راهنماییتان کنم."
            }
        }
    }
}
